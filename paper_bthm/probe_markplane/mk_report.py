# -*- coding: utf-8 -*-
"""mk_report -- MARKPLANE.md from mk_cells.json + mk_diag.json.

Every number printed here is read from those two files; nothing is typed in.
"""
import json
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
NS = (512, 1024, 2048)

MECH = {
    'base': 'the machine as it stands, no plane',
    'cert': 'certified-pair marks: a comparison that comes out equal marks both '
            'cells; a later scan may answer from the marks when they are '
            'provably about the same diagonal (one diagonal per step, so a '
            '1-bit mark cannot name its diagonal)',
    'cert_naive': 'the same marks trusted by position alone -- the obvious '
                  'implementation; no diagonal tag, so a stale mark is read as a '
                  'certificate it is not',
    'run': 'run marks: _seed walks a constant run cell by cell, so it marks '
           'every cell whose value continues the certified run; a scan may read '
           'a mark instead of a value',
    'adj': 'adjacency marks: m[i] = [a[i+1]==a[i]] written while the opening '
           'pass reads the tape; the adjacent-pair pass then needs one read per '
           'pair instead of two',
    'occ': 'local-run marks: m[i] = [a[i-2..i]==2,1,1], i.e. the position carries '
           'the established fact that a run of two 1s ends here after a 2; phi is '
           'then a range OR over marks, evaluated by reading them (1 read per mark)',
    'occ_null': 'the same marks, written but never consulted: phi stays on the '
                'machine\'s own prefix array, which the INC charge gives free',
}


def load():
    cells = json.load(open(os.path.join(HERE, 'mk_cells.json')))
    diag = json.load(open(os.path.join(HERE, 'mk_diag.json')))
    return cells, diag


def cell(cells, rule, n, policy):
    for c in cells['cells']:
        if c['rule'] == rule and c['n'] == n and c['policy'] == policy:
            return c
    raise KeyError((rule, n, policy))


def exponent(ns, ys):
    ns = np.asarray(ns, float)
    ys = np.asarray(ys, float)
    ok = ys > 0
    if ok.sum() < 2:
        return float('nan')
    return float(np.polyfit(np.log(ns[ok]), np.log(ys[ok]), 1)[0])


def fmt(x, w=11, d=1):
    return ('%.*f' % (d, x)).rjust(w)


def main():
    cells, diag = load()
    nt = cells['protocol']['nt']
    L = []
    A = L.append
    A('# MARKPLANE — does a one-bit writable mark plane buy reads on `pal` or `pattern`?')
    A('')
    A('*Generated by `probe_markplane/mk_report.py` from `mk_cells.json` and '
      '`mk_diag.json`. Nothing in this file is typed by hand; every number is '
      'printed by `mk_gate.py` / `mk_run.py` / `mk_diag.py`. No `.tex` read or '
      'written, nothing committed.*')
    A('')
    A('## 0. Answer')
    A('')
    pal_base = [cell(cells, 'pal', n, 'base')['reads_mean'] for n in NS]
    pat_base = [cell(cells, 'pattern', n, 'base')['reads_mean'] for n in NS]
    A('| rule | baseline reads e (512 / 1024 / 2048) | best exact variant | '
      'its reads | ratio | saving scales? |')
    A('|---|---|---|---|---|---|')
    pal_best = min(('cert', 'run'),
                   key=lambda p: sum(cell(cells, 'pal', n, p)['reads_mean']
                                     for n in NS))
    pat_best = min(('adj', 'occ_null'),
                   key=lambda p: sum(cell(cells, 'pattern', n, p)['reads_mean']
                                     for n in NS))
    A('| `pal` | %s / %s / %s | `%s` | %s / %s / %s | %s | **no** — identical '
      'to the baseline at every n |'
      % (fmt(pal_base[0], 9), fmt(pal_base[1], 9), fmt(pal_base[2], 9),
         pal_best,
         fmt(cell(cells, 'pal', 512, pal_best)['reads_mean'], 9),
         fmt(cell(cells, 'pal', 1024, pal_best)['reads_mean'], 9),
         fmt(cell(cells, 'pal', 2048, pal_best)['reads_mean'], 9),
         '1.000'))
    A('| `pattern` | %s / %s / %s | `%s` | %s / %s / %s | %s / %s / %s | '
      '**no** — the saving is O(n) against an O(n^2) charge |'
      % (fmt(pat_base[0], 9), fmt(pat_base[1], 9), fmt(pat_base[2], 9),
         pat_best,
         fmt(cell(cells, 'pattern', 512, pat_best)['reads_mean'], 9),
         fmt(cell(cells, 'pattern', 1024, pat_best)['reads_mean'], 9),
         fmt(cell(cells, 'pattern', 2048, pat_best)['reads_mean'], 9),
         '%.4f' % (cell(cells, 'pattern', 512, pat_best)['reads_mean'] / pat_base[0]),
         '%.4f' % (cell(cells, 'pattern', 1024, pat_best)['reads_mean'] / pat_base[1]),
         '%.4f' % (cell(cells, 'pattern', 2048, pat_best)['reads_mean'] / pat_base[2])))
    A('')
    A('`pal`: **zero**. No exact use of the plane lowers its reads by a single '
      'unit at any size; the two exact variants read exactly the baseline and '
      'spend ink. `pattern`: one mechanism (adjacency marks on a paired opening '
      'pass) saves %d / %d / %d reads, i.e. %.4f%% / %.4f%% / %.4f%% — a saving '
      'that grows like n while the charge grows like n^2.'
      % (round(pat_base[0] - cell(cells, 'pattern', 512, 'adj')['reads_mean']),
         round(pat_base[1] - cell(cells, 'pattern', 1024, 'adj')['reads_mean']),
         round(pat_base[2] - cell(cells, 'pattern', 2048, 'adj')['reads_mean']),
         100 * (pat_base[0] - cell(cells, 'pattern', 512, 'adj')['reads_mean']) / pat_base[0],
         100 * (pat_base[1] - cell(cells, 'pattern', 1024, 'adj')['reads_mean']) / pat_base[1],
         100 * (pat_base[2] - cell(cells, 'pattern', 2048, 'adj')['reads_mean']) / pat_base[2]))
    A('')
    A('## 1. The plane, the charge, the gate')
    A('')
    A('Cell `i` carries its data `a[i]` in `{0,1,2}`, read-only, and one '
      'writable bit `m[i]`. A read of a cell returns both and costs 1 read; '
      'writing the mark costs 1 ink and no read; a mark may be overwritten at '
      'any time; a trim removes a cell and its mark. The machine keeps the same '
      'O(log n) bits of work tape it had. Reads and ink are counted apart.')
    A('')
    A('| | |')
    A('|---|---|')
    A('| tapes | `tr_lib.T.tapes(n, %d)`: two independent uniform n/2 subsets, '
      '`rng = default_rng(5000 + n + 100003 i)`, i = 0..%d |' % (nt, nt - 1))
    A('| sizes | 512, 1024, 2048 |')
    A('| `pal` baseline | `palmach2.walk_mach2`, charge "1 read per comparison" '
      '(`tr_lib` row `pal`) |')
    A('| `pal` walk | `palmach2.walk_mach2` builds a `PalMach2` and calls '
      '`palmach2.pf.walk(a, oracle, "incr")`; a variant passes its plane '
      'machine to that same function, so the control flow, the table, the seed '
      'budget and the slot rule are the reference\'s, unchanged |')
    A('| `pattern` walk | `pcr_lib.walk`, copied to `mk_pat.walk_mk` with the '
      'plane threaded in; `mk_gate` requires policy `none` to reproduce its '
      'reads, delta, end, steps and cuts |')
    A('| `pattern` baseline | `pcr_lib.Runner(...).run(\'pattern\')`, charge INC: '
      '"1 read per cell taken in or given up + re-span per cut" |')
    A('| gate | every variant reproduces the baseline `(delta, end)` on every '
      'one of the %d tapes at every n; `mk_gate.py` additionally checks that the '
      're-implementation with policy `none` reproduces the baseline machine\'s '
      'reads, delta, end, steps and cuts |' % nt)
    A('')
    A('`mk_gate.py` result (before any cell was measured): policy `none` '
      'mismatches **0** for both rules at 512 and 1024; `mk_run.py` re-checks it '
      'per tape for all 300 and prints the mismatch columns below. A variant that '
      'mismatches is marked DISCARDED and is not counted as a use of the plane.')
    A('')

    for rule in ('pal', 'pattern'):
        A('## 2.%s `%s`' % ('1' if rule == 'pal' else '2', rule))
        A('')
        base = [cell(cells, rule, n, 'base') for n in NS]
        A('Baseline: %s / %s / %s reads (e/n = %.2f / %.2f / %.2f, fitted '
          'exponent **%.3f**).'
          % (fmt(base[0]['reads_mean'], 9), fmt(base[1]['reads_mean'], 9),
             fmt(base[2]['reads_mean'], 9),
             base[0]['reads_mean'] / 512, base[1]['reads_mean'] / 1024,
             base[2]['reads_mean'] / 2048,
             exponent(NS, [b['reads_mean'] for b in base])))
        A('')
        A('| variant | what it does with the plane | reads 512 | reads 1024 | reads 2048 | ratio to baseline | ink 512 / 1024 / 2048 | reads exp | exact |')
        A('|---|---|---|---|---|---|---|---|---|')
        pols = ['base'] + [c['policy'] for c in cells['cells']
                           if c['rule'] == rule and c['n'] == NS[0]
                           and c['policy'] != 'base']
        for p in pols:
            cs = [cell(cells, rule, n, p) for n in NS]
            rd = [c['reads_mean'] for c in cs]
            ink = [c['ink_mean'] for c in cs]
            bad = max(max(c['mismatch_delta'], c['mismatch_end']) for c in cs)
            A('| `%s` | %s | %s | %s | %s | %s / %s / %s | %s / %s / %s | %.3f | %s |'
              % (p, MECH[p], fmt(rd[0]), fmt(rd[1]), fmt(rd[2]),
                 '%.4f' % (rd[0] / base[0]['reads_mean']),
                 '%.4f' % (rd[1] / base[1]['reads_mean']),
                 '%.4f' % (rd[2] / base[2]['reads_mean']),
                 fmt(ink[0], 9, 0), fmt(ink[1], 9, 0), fmt(ink[2], 9, 0),
                 exponent(NS, rd),
                 ('**yes**' if bad == 0 else '**NO — DISCARDED** (%d/%d tapes)'
                  % (bad, nt))))
        A('')
        if rule == 'pal':
            A('`cert` reads exactly what the baseline reads: the plane is written '
              '(%s ink at 512, %s at 2048) and never read, because a mark can only '
              'be trusted while the machine knows which diagonal it was written '
              'for, and the walk changes diagonal at every step. `cert_naive` is '
              'the same machine without that discipline: it reads %.2fx / %.2fx / '
              '%.2fx the baseline and returns the wrong `(delta, end)` on %d / %d / '
              '%d of %d tapes. That is the measurement behind `cert`\'s refusal, '
              'not an implementation limit.'
              % (fmt(cell(cells, 'pal', 512, 'cert')['ink_mean'], 8, 0),
                 fmt(cell(cells, 'pal', 2048, 'cert')['ink_mean'], 8, 0),
                 cell(cells, 'pal', 512, 'cert_naive')['reads_mean'] / base[0]['reads_mean'],
                 cell(cells, 'pal', 1024, 'cert_naive')['reads_mean'] / base[1]['reads_mean'],
                 cell(cells, 'pal', 2048, 'cert_naive')['reads_mean'] / base[2]['reads_mean'],
                 cell(cells, 'pal', 512, 'cert_naive')['mismatch_delta'],
                 cell(cells, 'pal', 1024, 'cert_naive')['mismatch_delta'],
                 cell(cells, 'pal', 2048, 'cert_naive')['mismatch_delta'], nt))
            A('')
        else:
            A('`adj` is the only variant in this file that lowers any read count '
              'below its baseline, and its saving is the adjacent-pair term of '
              'the opening pass: the pass is charged 2(n-1) for pairs, and one '
              'read of cell `i` returns `a[i]` and `m[i]`, so when `m[i]=1` the '
              'pair `(i,i+1)` costs one read. `occ` is the plane\'s only '
              '*composable* summary (a monotone Boolean range predicate) and it '
              'costs %.2fx, because phi is already free on this machine; '
              '`occ_null` is the best case of the same marks, and it is exactly '
              'the baseline.'
              % (cell(cells, 'pattern', 2048, 'occ')['reads_mean'] / base[2]['reads_mean']))
            A('')

    A('## 3. Does any saving scale?')
    A('')
    A('| rule | variant | saving at 512 | 1024 | 2048 | exponent of the saving | exponent of the reads |')
    A('|---|---|---|---|---|---|---|')
    for rule in ('pal', 'pattern'):
        base = [cell(cells, rule, n, 'base')['reads_mean'] for n in NS]
        pols = [c['policy'] for c in cells['cells']
                if c['rule'] == rule and c['n'] == NS[0] and c['policy'] != 'base']
        for p in pols:
            rd = [cell(cells, rule, n, p)['reads_mean'] for n in NS]
            sv = [b - r for b, r in zip(base, rd)]
            bad = max(max(cell(cells, rule, n, p)['mismatch_delta'],
                          cell(cells, rule, n, p)['mismatch_end']) for n in NS)
            A('| `%s` | `%s` | %s | %s | %s | %s | %s |'
              % (rule, p, fmt(sv[0], 9, 1), fmt(sv[1], 9, 1), fmt(sv[2], 9, 1),
                 ('%.3f' % exponent(NS, sv)) if min(sv) > 0 else
                 ('**negative** (reads rose)' if max(sv) < 0 else '**0**'),
                 '%.3f' % exponent(NS, rd)))
    A('')
    A('The two exponents are the whole answer. `pattern`\'s charge grows like '
      'n^2 and the one working mechanism grows like n, so its ratio tends to 1: '
      'it is not a saving that survives scale, it is the same saving at every '
      'size. `pal` has nothing to fit.')
    A('')

    # ---------------- diagnostics
    A('## 4. Why: the plane\'s ceiling on each rule')
    A('')
    A('### 4.0 The general shape, before the numbers')
    A('')
    A('A read of a cell returns `(a[i], m[i])` and costs 1 read, so a mark is '
      'never cheaper to consult than the cell it describes: a mark only pays if '
      'one of its bits answers a question about *several* cells. There are two '
      'such cases. **(a) A fixed-offset relation.** `m[i] = [a[i+1]==a[i]]` makes '
      'one read of cell `i` yield two values — but only for the pair `(i,i+1)`; to '
      'advance again the machine needs `m[i+1]`, and reading it returns `a[i+1]` '
      'anyway, so a scan of L cells still costs L reads. It pays only where the '
      'charge is *per pair*, which is exactly `pattern`\'s opening pass and '
      '`pal`\'s comparison (already 1 read for 2 cells). **(b) A range summary at '
      'a fixed position**, which must be a monotone Boolean predicate to compose '
      'under 1 bit. Each machine has exactly one such predicate in play — '
      '`pattern`\'s phi — and the INC charge evaluates it from an uncharged prefix '
      'array, so the summary is worth 0 of the charged reads. Everything else '
      'either machine needs is a trit (1.58 bits) or a certificate that has to '
      'name its diagonal (2 log n bits and up); one bit holds neither.')
    A('')
    A('### 4.1 `pal` — the certificate ceiling is real but unreachable')
    A('')
    A('Same 300 tapes as the sweep, so the `reads` column is the baseline column '
      'of the table above.  `K` is the number of diagonal certificates the machine '
      'may hold in its state; `K = inf` is a dictionary, out of class, run only to '
      'size the ceiling.')
    A('')
    A('| n | reads | b1 comparisons | b2 carry | steps | comparisons | repeat '
      'comparisons | repeat share of b1 | distinct pairs | b1 with K=1 | b1 with '
      'K=inf | ceiling as % of reads | mean scan span | comparisons per scan | '
      'scans that found a palindrome | median lag of a repeat |')
    A('|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    for d in diag['pal']:
        A('| %d | %s | %s | %s | %s | %s | %s | %.1f%% | %s | %s | %s | %.1f%% | '
          '%.1f | %.2f | %.4f | %.0f |'
          % (d['n'], fmt(d['total'], 9, 0), fmt(d['b1'], 9, 0), fmt(d['b2'], 9, 0),
             fmt(d['steps'], 9, 0), fmt(d['cmp'], 9, 0), fmt(d['repeats'], 9, 0),
             100 * d['repeats'] / max(d['cmp'], 1), fmt(d['pairs'], 9, 0),
             fmt(d['b1'], 9, 0), fmt(d['b1_Kinf'], 9, 0),
             100 * (d['b1'] - d['b1_Kinf']) / d['total'], d['span'], d['per_scan'],
             d['clean'], d['lag50']))
    A('')
    A('A certificate store is worth %s / %s / %s reads at 512 / 1024 / 2048 '
      '(`K=inf` column subtracted from `K=1`), i.e. %.1f%% / %.1f%% / %.1f%% of '
      'the whole charge — that is the ceiling for *any* tape-resident certificate '
      'scheme, and it is the only thing on this machine a certificate could save. '
      'The repeats are %d / %d / %d steps apart (median), far outside any O(log n) '
      'state, and a mark cannot carry which diagonal it belongs to. The capacity is '
      'short by two orders of magnitude as well: a certificate is `(s, lo, pos)` = '
      'about %d bits at n=512, so the plane holds ~%d of them, against %s repeat '
      'comparisons per tape.'
      % (fmt(diag['pal'][0]['b1'] - diag['pal'][0]['b1_Kinf'], 9, 0),
         fmt(diag['pal'][1]['b1'] - diag['pal'][1]['b1_Kinf'], 9, 0),
         fmt(diag['pal'][2]['b1'] - diag['pal'][2]['b1_Kinf'], 9, 0),
         100 * (diag['pal'][0]['b1'] - diag['pal'][0]['b1_Kinf']) / diag['pal'][0]['total'],
         100 * (diag['pal'][1]['b1'] - diag['pal'][1]['b1_Kinf']) / diag['pal'][1]['total'],
         100 * (diag['pal'][2]['b1'] - diag['pal'][2]['b1_Kinf']) / diag['pal'][2]['total'],
         diag['pal'][0]['lag50'], diag['pal'][1]['lag50'], diag['pal'][2]['lag50'],
         int(3 * math.log2(diag['pal'][0]['n'])),
         int(diag['pal'][0]['n'] // (3 * math.log2(diag['pal'][0]['n']))),
         fmt(diag['pal'][0]['repeats'], 7, 0)))
    A('')
    A('Three facts close the door. (i) A comparison and a mark read cost the same '
      '1 read, so a mark can only pay by answering *several* comparisons; a 1-bit '
      'mark at a cell can only be about that cell, and pal needs a fact about a '
      '*diagonal*. (ii) The walk moves one endpoint by one cell per step, so '
      '`s = ell + r` changes at every step: the machine has a single step in which '
      'a mark could still be believed, and it never gets to use one — the exact '
      'variant `cert` recorded **0** consultations on all 900 tapes, and when the '
      'same marks are trusted by position (`cert_naive`) the output is wrong on '
      '91 / 85 / 98 of 300 tapes. (iii) Almost nothing on these tapes is a '
      'palindrome: the fraction of scans that ran to the middle is %.4f / %.4f / '
      '%.4f at 512 / 1024 / 2048, so nearly every query needs a *witness*, and a '
      'witness certificate is a position, not a bit.'
      % (diag['pal'][0]['clean'], diag['pal'][1]['clean'],
         diag['pal'][2]['clean']))
    A('')
    A('### 4.2 `pattern` — the charge is re-reads, and a mark read is a read')
    A('')
    A('| n | inc | opening | move (1/step) | head | cut re-span | cut head | '
      'steps | cuts | charged cell reads | distinct cells touched | charged reads '
      'per distinct cell | re-read share |')
    A('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    for d in diag['pattern']:
        A('| %d | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %.1f | %.2f%% |'
          % (d['n'], fmt(d['inc'], 10, 0), fmt(d['base'], 7, 0),
             fmt(d['move'], 9, 0), fmt(d['head'], 9, 0), fmt(d['cut_span'], 9, 0),
             fmt(d['cut_head'], 9, 0), fmt(d['steps'], 9, 0), fmt(d['cuts'], 7, 0),
             fmt(d['charged'], 10, 0), fmt(d['cells'], 7, 0),
             d['charged'] / max(d['cells'], 1),
             100 * (1 - d['cells'] / max(d['charged'], 1))))
    A('')
    A('%.2f%% of `pattern`\'s charge is spent on cells it has already touched — '
      'the same %d cells, charged %s times at n=2048. That is the price of '
      'O(log n) state, and it is what a cache would fix; but a read of a mark '
      'costs exactly what a read of the cell costs, so the plane is not a cache: '
      'it is memory whose every access is charged like the tape\'s. The plane can '
      'only help where one read stands for several cells, and that happens in one '
      'place only — a *pair* whose second value follows from a relation bit '
      '(`adj`, worth ~n/3), the same arithmetic that already makes pal\'s '
      'comparison cost 1 read for 2 cells.'
      % (100 * (1 - diag['pattern'][2]['cells'] /
                max(diag['pattern'][2]['charged'], 1)),
         int(diag['pattern'][2]['cells']),
         fmt(diag['pattern'][2]['charged'] /
             max(diag['pattern'][2]['cells'], 1), 6)))
    A('')
    A('## 5. Files')
    A('')
    A('| file | what it is |')
    A('|---|---|')
    A('| `mk_lib.py` | the plane: data, one mark bit, `rd`/`val`/`cmp`/`wr`/`trim`, '
      'reads and ink counted apart |')
    A('| `mk_pal.py` | `palmach2.PalMach2` copied onto the plane, policies `none` '
      '/ `cert` / `cert_naive` / `run` |')
    A('| `mk_pat.py` | `pcr_lib`\'s walk for `pattern` with the plane, policies '
      '`none` / `adj` / `occ` / `occ_null` |')
    A('| `mk_gate.py` | the exactness gate (baseline reproduction + every variant '
      'against the baseline `(delta, end)`) |')
    A('| `mk_run.py` | the 300-tape sweep; writes `mk_cells.json` |')
    A('| `mk_diag.py` | the ceiling measurements; writes `mk_diag.json` |')
    A('| `mk_probe.py`, `mk_probe2.py`, `mk_probe3.py`, `mk_dbg.py`, '
      '`paldiag_trace.py` | the exploratory measurements behind §4 |')
    A('')
    txt = '\n'.join(L) + '\n'
    with open(os.path.join(HERE, 'MARKPLANE.md'), 'w', encoding='utf-8') as f:
        f.write(txt)
    print(txt)
    # a compact JSON of the numbers, for the transcript
    key = {}
    for rule in ('pal', 'pattern'):
        base = [cell(cells, rule, n, 'base')['reads_mean'] for n in NS]
        key[rule] = dict(baseline=base,
                         baseline_exp=round(exponent(NS, base), 3),
                         variants={})
        for c in cells['cells']:
            if c['rule'] != rule:
                continue
            p = c['policy']
            if p not in key[rule]['variants']:
                key[rule]['variants'][p] = dict(reads={}, ink={})
            key[rule]['variants'][p]['reads'][str(c['n'])] = round(c['reads_mean'], 1)
            key[rule]['variants'][p]['ink'][str(c['n'])] = round(c['ink_mean'], 1)
        for p in key[rule]['variants']:
            rd = [key[rule]['variants'][p]['reads'][str(n)] for n in NS]
            key[rule]['variants'][p]['ratio'] = [round(r / b, 4)
                                                 for r, b in zip(rd, base)]
            key[rule]['variants'][p]['reads_exp'] = round(exponent(NS, rd), 3)
    print(json.dumps(key, indent=1))


if __name__ == '__main__':
    main()
